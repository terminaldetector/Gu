'use strict';
// G1 reward_port_check: the AGOD reward port (app/src/main/assets/lab/agod-reward-sink.js)
// holds the reward rules on the consumer side, with no neural backend anywhere.
//
// Part A - the port on synthetic packets: no reward, one payment per event,
//   PROVISIONAL apart from VERIFIED, a paid packet without a value is never 0,
//   out-of-order, stale epochs after a restore, ROM change, invalidation, the
//   executed action, replay, frozen mode, ledger import. It also keeps the
//   invariant of the deleted FdbUnknownRewardCheck on a minimal reference
//   consumer: UNKNOWN routed as boundary leaves a learner untouched, the same
//   interval fed as a numeric 0 would move it.
// Part B - the real chain: AGOD discovery on the generated NES test cartridge ->
//   profile -> live objective on its own live core -> port. The objective-level
//   invariants of agod_l1_bridge_check (profile binding, refusal of another
//   cartridge or pad, strict default, ledger across a restart, override, mask
//   mismatch, revocation) are kept here, without FDB.
// NO COMMERCIAL ROM; the cartridges are generated by tools/make_agod_*_rom.py.
const fs=require('fs'),os=require('os'),path=require('path'),crypto=require('crypto'),{execFileSync}=require('child_process');
const A=path.resolve(__dirname,'../app/src/main/assets/lab');
const Sink=require(path.join(A,'agod-reward-sink.js'));
const out=[],fail=[];
const ok=(c,m)=>{out.push((c?'  ok    ':'  FAIL  ')+m);if(!c)fail.push(m);return c;};
const has=(o,k)=>Object.prototype.hasOwnProperty.call(o,k);
const H=c=>crypto.createHash('sha256').update(c).digest('hex');
const ctxA={romSha256:H('rom-a'),platform:'nes',coreRevision:'jsnes',goalId:'g1'};
const ctxB={romSha256:H('rom-b'),platform:'nes',coreRevision:'jsnes',goalId:'g1'};
const EX={mask:4,frames:12,complete:true,manualOverride:false};
const meta=(sink,decision,endFrame,extra)=>({epoch:sink.epoch(),decision,endFrame,...sink.context(),executed:EX,...(extra||{})});
const V=(id,value,extra)=>({status:'VERIFIED',goalId:'g1',eventId:id,value,executedAction:{mask:4},...(extra||{})});
const P=(id,value)=>({status:'PROVISIONAL',goalId:'g1',eventId:id,value,channel:'provisional-progress'});
const U={status:'UNKNOWN',goalId:'g1',reason:'no verified event in this interval'};

/* ======================= Part A: the port ======================= */
{
 /* no reward: nothing numeric reaches the consumer */
 const s=Sink.createRewardSink({context:ctxA});
 const o=[0,1,2].map(k=>s.accept(U,meta(s,k,12*(k+1))));
 ok(o.every(x=>x.kind==='UNKNOWN'&&!has(x,'value')&&x.route==='boundary'&&!x.accepted&&!x.learnable),'UNKNOWN has no value key and routes to boundary');
 const t=s.totals();
 ok(t.unknown===3&&t.verified.count===0&&t.provisional.count===0&&t.verified.sum===0,'no reward: totals stay empty, UNKNOWN is only counted');
}
{
 const s=Sink.createRewardSink({context:ctxA});
 const a=s.accept(V('e1',-1),meta(s,0,12)),b=s.accept(V('e1',-1),meta(s,1,24));
 ok(a.accepted&&a.confirmed&&a.route==='feedback'&&a.value===-1&&a.channel==='verified','a VERIFIED event pays once, confirmed');
 ok(!b.accepted&&b.code==='duplicate'&&!has(b,'value'),'the same event again is a duplicate and pays nothing');
 const p=s.accept(P('p1',0.25),meta(s,2,36));
 ok(p.accepted&&!p.confirmed&&p.channel==='provisional','PROVISIONAL is paid on its own channel and is not confirmed');
 const t=s.totals();
 ok(t.verified.count===1&&t.verified.sum===-1&&t.provisional.count===1&&t.provisional.sum===0.25,'verified and provisional sums are kept apart');
 const noValue=s.accept({status:'VERIFIED',goalId:'g1',eventId:'e2'},meta(s,3,48));
 const nan=s.accept(V('e3',NaN),meta(s,4,60));
 ok(noValue.code==='malformed'&&nan.code==='malformed'&&!has(noValue,'value')&&!has(nan,'value'),'a VERIFIED packet without a finite value is rejected, never read as 0');
 ok(s.accept({status:'PAID',eventId:'x',value:1},meta(s,5,72)).code==='malformed','an unknown packet kind is refused');
}
{
 /* out of order */
 const s=Sink.createRewardSink({context:ctxA});
 s.accept(V('e1',-1),meta(s,5,60));
 const back=s.accept(V('e2',-1),meta(s,4,72)),frame=s.accept(V('e3',-1),meta(s,6,48));
 ok(back.code==='out-of-order'&&frame.code==='out-of-order','an earlier decision or an earlier end frame is out of order');
 const ok2=s.accept(V('e4',-1),meta(s,7,72));
 ok(ok2.accepted,'the next decision in order still pays');
 ok(s.accept(U,meta(s,8,84)).kind==='UNKNOWN'&&s.accept(V('e5',-1),meta(s,8,96)).code==='out-of-order','the cursor advances on unpaid packets too: a repeated decision index is late');
}
{
 /* restore: a boundary opens a new epoch; what was settled before it is stale; paid ids stay paid */
 const s=Sink.createRewardSink({context:ctxA});
 const before=meta(s,0,12);s.accept(V('e1',-1),before);
 const settledBefore=meta(s,1,24);
 const e=s.boundary('restore');
 ok(e===1&&s.epoch()===1,'a restore opens epoch 1');
 const stale=s.accept(V('e2',-1),settledBefore);
 ok(stale.code==='stale-epoch'&&!has(stale,'value'),'a packet settled before the restore is stale');
 ok(s.accept(V('e1',-1),meta(s,0,12)).code==='duplicate','an event paid before the restore is not paid again after it');
 ok(s.accept(V('e2',-1),meta(s,1,24)).accepted,'after the restore the epoch has its own cursor: the next decision pays a new event');
 ok(s.totals().boundaries.restore===1,'boundaries are counted by reason (frozen evaluation can assert zero restores)');
}
{
 /* ROM change, and back */
 const s=Sink.createRewardSink({context:ctxA});
 s.accept(V('e1',-1),meta(s,0,12));const lateA=meta(s,1,24);
 s.boundary('rom-change',ctxB);
 ok(s.accept(V('e9',-1),lateA).code==='stale-epoch','a packet from the previous ROM is stale after the switch');
 ok(s.accept(V('e9',-1),{...meta(s,0,12),...ctxA}).code==='context','a packet naming another ROM is refused');
 ok(s.accept(V('e1',-1),meta(s,0,12)).accepted,'ROM B has its own ledger: its event e1 is a different event');
 ok(s.accept(V('e2',-1,{goalId:'g2'}),meta(s,1,24)).code==='context','a packet for another goal is refused');
 s.boundary('rom-change',ctxA);
 ok(s.accept(V('e1',-1),meta(s,0,12)).code==='duplicate','back on ROM A, its paid event is still paid');
}
{
 /* invalidation */
 const s=Sink.createRewardSink({context:ctxA});
 const inv=s.accept({status:'INVALIDATED',goalId:'g1',eventId:'e1',reason:'this event was already credited (ledger)'},meta(s,0,12));
 ok(inv.kind==='INVALIDATED'&&!has(inv,'value')&&inv.route==='boundary','an INVALIDATED packet passes as a boundary, with no value');
 s.revoke('contradicted by re-verification');
 const late=s.accept(V('e2',-1),meta(s,1,24));
 ok(late.kind==='INVALIDATED'&&!has(late,'value')&&/revoked/.test(late.reason),'after revoke() nothing pays');
 s.boundary('rom-change',ctxB);
 ok(s.accept(V('e3',-1),meta(s,0,12)).accepted,'a new context is not bound by the previous objective\'s revocation');
}
{
 /* the reward belongs to the executed action */
 const s=Sink.createRewardSink({context:ctxA});
 const inc=s.accept(V('e1',-1),meta(s,0,12,{executed:{...EX,complete:false}}));
 const man=s.accept(V('e2',-1),meta(s,1,24,{executed:{...EX,manualOverride:true}}));
 const other=s.accept(V('e3',-1),meta(s,2,36,{executed:{...EX,mask:8}}));
 ok([inc,man,other].every(x=>x.code==='not-executed'&&!has(x,'value')),'incomplete, overridden or other-mask actions are not paid');
 ok(s.accept(V('e1',-1),meta(s,3,48)).accepted,'a refused event can still be paid once for the action that really ran');
}
{
 /* replay: the same stream gives the same outcomes; replaying into the same port pays nothing new */
 const stream=[];const s=Sink.createRewardSink({context:ctxA});
 const push=(p,m)=>{stream.push({p,m});return s.accept(p,m);};
 const first=[push(V('e1',-1),meta(s,0,12)),push(U,meta(s,1,24)),push(P('p1',.25),meta(s,2,36)),push(V('e1',-1),meta(s,3,48))];
 const fresh=Sink.createRewardSink({context:ctxA});
 const again=stream.map(({p,m})=>fresh.accept(p,m));
 ok(JSON.stringify(again)===JSON.stringify(first)&&JSON.stringify(fresh.totals())===JSON.stringify(s.totals()),'replay into a fresh port is deterministic');
 s.boundary('replay');
 const replayed=stream.map(({p,m})=>s.accept(p,{...m,epoch:s.epoch()}));
 ok(replayed.filter(x=>x.accepted).length===0&&replayed.filter(x=>x.code==='duplicate').length===3,'replaying the same stream into the same port pays nothing new');
 const imported=Sink.createRewardSink({context:ctxA,ledger:s.exportLedger()});
 ok(imported.accept(V('e1',-1),meta(imported,0,12)).code==='duplicate','an imported ledger keeps paid events paid across a restart');
}
{
 const s=Sink.createRewardSink({context:ctxA,mode:'frozen'});
 const x=s.accept(V('e1',-1),meta(s,0,12));
 ok(x.accepted&&x.learnable===false&&s.mode()==='frozen','frozen mode reports an accepted outcome but never as learnable');
 let threw=0;for(const bad of [{},{...ctxA,romSha256:'abc'},{...ctxA,platform:''}])try{Sink.createRewardSink({context:bad});}catch(_){threw++;}
 ok(threw===3,'a port is not created without a full game context');
}
{
 /* the FdbUnknownRewardCheck invariant, on a minimal reference consumer: a
    running-baseline learner with an eligibility trace */
 const learner=()=>({baseline:0,updates:0,trace:1,
  feedback(r){this.baseline+=.1*(r-this.baseline);this.updates++;this.trace=1;},boundary(){this.trace=0;}});
 const route=(l,x)=>x.route==='feedback'&&x.learnable?l.feedback(x.value):l.boundary();
 const s=Sink.createRewardSink({context:ctxA});
 const l=learner();for(let k=0;k<8;k++)route(l,s.accept(V('k'+k,1,{executedAction:{mask:4}}),meta(s,k,12*(k+1))));
 const b=l.baseline,u=l.updates;
 route(l,s.accept(U,meta(s,8,108)));
 ok(l.baseline===b&&l.updates===u&&l.trace===0,'UNKNOWN through the port leaves the learner untouched and clears its temporal credit');
 const naive=learner();naive.baseline=b;naive.feedback(0);
 ok(naive.baseline<b,'the same interval fed as a numeric 0 would move the baseline - which is why UNKNOWN is not 0');
}

/* ======================= Part B: the real chain ======================= */
const jsnes=require(path.join(A,'jsnes.min.js'));globalThis.jsnes=jsnes;
globalThis.FlyPlatforms=require(path.join(A,'platforms.js'));
for(const f of ['agod-ram.js','agod-causal.js','agod-goals.js','agod-reward.js','agod-evidence.js',
 'agod-candidates.js','agod-consumers.js','agod-platform-driver.js','agod-pipeline.js','agod-goal-dto.js','agod-objective.js'])require(path.join(A,f));
const PD=globalThis.FlyAgodPlatformDriver,Pipeline=globalThis.FlyAgodPipeline,Dto=globalThis.FlyAgodGoalDto,Objective=globalThis.FlyAgodObjective;
const MODULES={Dto,Reward:globalThis.FlyAgodReward,Evidence:globalThis.FlyAgodEvidence,Ram:globalThis.FlyAgodRam};
const work=fs.mkdtempSync(path.join(os.tmpdir(),'reward-port-'));
const HOLD=4,RELEASE=8;
function cartridge(generator,tag,extra){
 const rom=path.join(work,tag+'.json');
 execFileSync(process.env.PYTHON||'python3',[path.join(__dirname,generator),'--out',rom,...(extra||[])]);
 return Buffer.from(JSON.parse(fs.readFileSync(rom)).base64,'base64');
}
function discover(bytes){
 const built=PD.createNesSync({romBytes:bytes,jsnes,frameBudget:600000});
 for(let i=0;i<120;i++)built.core.frame();
 const romSha256=H(bytes);
 const config={romHash:romSha256,coreRevision:'jsnes',profileRevision:'agod-reward-port',typeEvents:30};
 const result=Pipeline.run(built.driver,config);
 const dto=Dto.fromPipelineResult(result,{...config,contextKey:romSha256+'/jsnes',platform:'nes',driverRevision:built.driverRevision});
 const identity={romSha256,platform:'nes',coreRevision:'jsnes',detectorRevision:Pipeline.PIPELINE_REVISION,
  actionSpec:built.capabilities.actionSpec,padType:built.capabilities.padType,observedRamBytes:built.capabilities.observedRamBytes};
 built.dispose();return {status:result.status,dto,identity};
}
/* the live game on its own core; its frame counter never rewinds with the game */
function live(bytes){
 const core=new jsnes.NES({onFrame(){},onAudioSample(){}});core.loadROM(bytes.toString('latin1'));
 for(let i=0;i<120;i++)core.frame();
 let frame=0;
 return {save:()=>JSON.stringify(core.toJSON()),restore:s=>core.fromJSON(JSON.parse(s)),ram:()=>core.cpu.mem.slice(0,0x800),
  step(mask){for(let b=0;b<8;b++)(mask&(1<<b)?core.buttonDown:core.buttonUp).call(core,1,b);
   for(let i=0;i<HOLD;i++)core.frame();for(let b=0;b<8;b++)core.buttonUp(1,b);for(let i=0;i<RELEASE;i++)core.frame();
   frame+=HOLD+RELEASE;return frame;}};
}

const positive=cartridge('make_agod_test_rom.py','positive',['--seed','0','--backdrop','0x30']);
const found=discover(positive);
ok(found.status==='VERIFIED','discovery reaches VERIFIED on the isolated core');
const profile=Objective.createProfile(found.dto,found.identity,MODULES);
ok(profile.status==='PROFILE','the VERIFIED goal becomes an objective profile');
ok(Objective.matches(profile,found.identity).ok,'the profile matches the game it was proved on');
const other=Objective.matches(profile,{...found.identity,romSha256:H('another cartridge')});
ok(!other.ok&&/romSha256/.test(other.problems.join()),'and refuses a different cartridge');
ok(Objective.createLiveReward(profile,MODULES,{identity:{...found.identity,padType:6}}).status==='REFUSED','no live objective when the pad layout differs from the proof');
const liveReward=o=>Objective.createLiveReward(profile,MODULES,{identity:found.identity,...(o||{})});
ok(liveReward().policy==='strict','the default policy is strict: a provisional gain pays only when asked for');
const none=discover(cartridge('make_agod_sequence_rom.py','refused',[]));
ok(none.status==='REFUSED'&&Objective.createProfile(none.dto,none.identity,MODULES).status==='REFUSED','a cartridge discovery refuses yields no profile, so no packet ever reaches a port');

const context={romSha256:found.identity.romSha256,platform:'nes',coreRevision:'jsnes',goalId:profile.goal.id};
const executed=mask=>({mask,frames:HOLD+RELEASE,complete:true,manualOverride:false});
const interval=(game,mask)=>{const before=game.ram(),endFrame=game.step(mask),after=game.ram();
 return {ramBefore:before,ramAfter:after,endFrame,executed:executed(mask),requestedMask:mask,phase:'PLAYING'};};
{
 const reward=liveReward(),game=live(positive),sink=Sink.createRewardSink({context});
 let k=0;const metaOf=sample=>({epoch:sink.epoch(),decision:k++,endFrame:sample.endFrame,...context,executed:sample.executed});
 const send=(packet,sample)=>sink.accept(packet,metaOf(sample));
 /* restore: a loss settled before a savestate restore is stale; the same loss
    re-lived from the restored state is a new event (the live frame counter
    never rewinds) and pays once. (On this cartridge a cost press lands about
    one time in three, so the snapshot is taken right before a press that does.) */
 const snap=game.save();
 const lost=interval(game,profile.actions.cost),lostP=reward.observe(lost),lostMeta=metaOf(lost);
 ok(lostP.status==='VERIFIED','the first cost press from the start is a verified loss');
 game.restore(snap);sink.boundary('restore');k=0;
 const stale=sink.accept(lostP,lostMeta);
 ok(stale.code==='stale-epoch'&&!has(stale,'value'),'a verified packet settled before a savestate restore is stale after it and pays nothing');
 const cost=interval(game,profile.actions.cost);
 const first=reward.observe(cost),paid=send(first,cost);
 ok(first.status==='VERIFIED'&&first.eventId!==lostP.eventId&&paid.accepted&&paid.confirmed&&paid.value<0,'the loss re-lived after the restore is a new event: it reaches the consumer once, confirmed and negative ('+paid.value+')');
 const repeat=reward.observe(cost);
 ok(repeat.status==='INVALIDATED'&&send(repeat,cost).route==='boundary','the objective refuses the same event again, and the port routes it to a boundary');
 ok(send(first,cost).code==='duplicate','a consumer that re-sends the paid packet is refused by the port\'s own ledger');
 const idle=interval(game,0),u=reward.observe(idle),uo=send(u,idle);
 ok(u.status==='UNKNOWN'&&uo.kind==='UNKNOWN'&&!has(uo,'value'),'an idle interval is UNKNOWN end to end, with no value');
 const restarted=liveReward({sessionId:first.eventId.split(':')[0],ledger:reward.exportLedger()});
 ok(restarted.observe(cost).status==='INVALIDATED','the objective\'s ledger survives a restart');
 const manual=liveReward().observe({...cost,executed:{...cost.executed,manualOverride:true}});
 ok(manual.status==='INVALIDATED'&&!has(manual,'value'),'a human override in the interval pays nothing');
 ok(liveReward().observe({...cost,requestedMask:0}).status==='INVALIDATED','an executed mask other than the requested one pays nothing');
 const revoked=liveReward();revoked.revoke('contradicted by re-verification');
 const lateSample=interval(game,profile.actions.cost),late=revoked.observe(lateSample);
 ok(late.status==='INVALIDATED'&&send(late,lateSample).route==='boundary','after revocation the objective pays nothing and the port routes a boundary');
 const t=sink.totals();
 ok(t.verified.count===1&&t.provisional.count===0&&t.boundaries.restore===1&&(t.rejected['stale-epoch']||0)===1&&(t.rejected.duplicate||0)===1,'totals: 1 verified payment, no provisional under the strict policy, 1 restore, 1 stale and 1 duplicate refusal');
}
{
 /* the aggressive tier: a progress gain arrives on the provisional channel, never confirmed */
 const reward=liveReward({policy:'aggressive'}),game=live(positive),sink=Sink.createRewardSink({context});
 let provisional=null;
 for(let k=0;k<40&&!provisional;k++){const s=interval(game,profile.actions.effect),p=reward.observe(s);
  const o=sink.accept(p,{epoch:sink.epoch(),decision:k,endFrame:s.endFrame,...context,executed:s.executed});
  if(p.status==='PROVISIONAL')provisional=o;}
 ok(provisional&&provisional.accepted&&provisional.channel==='provisional'&&!provisional.confirmed,'a real progress gain is paid on the provisional channel and is not confirmed');
}
fs.rmSync(work,{recursive:true,force:true});
console.log(out.join('\n'));
console.log(fail.length?'FAIL - '+fail.length+' of '+out.length:'PASS - '+out.length+'/'+out.length+' reward-port invariants (synthetic port + real AGOD chain, no neural backend)');
process.exitCode=fail.length?1:0;
