#!/usr/bin/env bash
# Build a SET of tech-test APKs that install side by side on one device.
#
# Each APK answers one question, so a failure on the phone points at a cause
# instead of at "the app". Every APK gets its own applicationId
# (org.node.flyconsole.nes.tech.tNN), its own launcher label (FC-TNN ...),
# the connectomes it needs and nothing else, and its own AGOD settings written
# into lab/techtest-config.js. The ordinary app (org.node.flyconsole.nes) is not
# replaced by any of them.
#
# Output: OUT_DIR (default ./techtest-apks) with the APKs, SHA256SUMS and
# TECHTEST_SET.md. Each APK is checked after the build: its package name, its
# label, which connectomes are really inside it, and the config it carries.
#
# The working tree is restored afterwards: techtest-config.js goes back to the
# committed default even if a build fails.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT_DIR="${OUT_DIR:-techtest-apks}"
mkdir -p "$OUT_DIR"
CONFIG=app/src/main/assets/lab/techtest-config.js
AAPT2="${ANDROID_HOME:-/opt/android-sdk}/build-tools/35.0.0/aapt2"
# the default config is restored from a copy, not from git, so this also works
# before the file is committed and never discards an uncommitted edit to it
DEFAULT_CONFIG=$(mktemp)
cp "$CONFIG" "$DEFAULT_CONFIG"
trap 'cp "$DEFAULT_CONFIG" "$CONFIG"; rm -f "$DEFAULT_CONFIG"' EXIT

# id | label | bundled connectomes | default connectome | autostart | policy | retry s | question
SET=$(cat <<'EOF'
T01|FC-T01 Shell|none|flywire-v783|false|aggressive|0|Starts at all? Manual play with no connectome bundled (loading one must fail cleanly).
T02|FC-T02 FlyWire|flywire|flywire-v783|false|aggressive|0|FlyWire 783 loads and drives the agent on this device; AGOD off.
T03|FC-T03 MaleCNS|male|male-cns-v1.0|false|aggressive|0|Male CNS loads and fits in memory on this device; AGOD off.
T04|FC-T04 Both noAGOD|both|flywire-v783|false|aggressive|0|Both connectomes bundled, switching between them; AGOD off.
T05|FC-T05 AGOD button|flywire|flywire-v783|false|aggressive|0|AGOD only when the button is pressed: does a run finish and does the status line say so?
T06|FC-T06 AGOD auto|flywire|flywire-v783|true|aggressive|0|Production behaviour: background AGOD after ROM load, aggressive reward tier.
T07|FC-T07 AGOD strict|flywire|flywire-v783|true|strict|0|Background AGOD, verified losses only (no progress tier): compare with T06.
T08|FC-T08 AGOD fast|flywire|flywire-v783|true|aggressive|10|Background AGOD retried every 10 s once the game advances: CPU/battery/heat stress.
T09|FC-T09 Full FlyWire|both|flywire-v783|true|aggressive|0|Release candidate: both connectomes, FlyWire by default, background AGOD.
T10|FC-T10 Full MaleCNS|both|male-cns-v1.0|true|aggressive|0|Release candidate with Male CNS by default, background AGOD.
EOF
)
{
 echo "# FlyConsole tech-test APK set"
 echo
 echo "- Commit: \`$(git rev-parse HEAD)\`"
 echo "- Base version: 2.3.0-agod (versionCode 43); each APK adds -TNN to the version name."
 echo "- Signature: Android debug key of the build machine. Not a release signature."
 echo "- All ten install side by side, and next to the normal app; each has its own data."
 echo "- GPU inference is not a separate APK: it is the 'Backend' switch inside any of them."
 echo "- WebView is debuggable in all of them (debug builds): chrome://inspect over USB."
 echo
 echo "| APK | Package | Label | Connectomes inside | Default | AGOD autostart | Policy | Retry | Size | Question |"
 echo "|---|---|---|---|---|---|---|---|---|---|"
} > "$OUT_DIR/TECHTEST_SET.md"
: > "$OUT_DIR/SHA256SUMS"

while IFS='|' read -r id label assets connectome autostart policy retry question; do
 [ -n "$id" ] || continue
 lower=$(echo "$id" | tr 'A-Z' 'a-z')
 retry_js=$([ "$retry" = 0 ] && echo "" || echo "window.GU_AGOD_RETRY_SECONDS=$retry;")
 cat > "$CONFIG" <<JS
/* Tech-test build $id - generated by tools/build_techtest_set.sh; not committed. */
'use strict';
window.GU_TECH=Object.freeze({id:'$id',label:'$label',assets:'$assets',defaultConnectome:'$connectome',
 agodAutostart:$autostart,agodPolicy:'$policy',agodRetrySeconds:${retry},question:$(printf '%s' "$question" | python3 -c 'import json,sys;print(json.dumps(sys.stdin.read()))')});
window.GU_AGOD_AUTOSTART=$autostart;
window.GU_AGOD_POLICY='$policy';
$retry_js
JS
 echo "=== $id: $label ($assets, default $connectome, autostart $autostart, $policy)"
 # clean: an incremental asset merge keeps connectomes a previous variant packaged
 gradle clean assembleDebug --no-daemon -q \
  -PguTechId="$id" -PguTechLabel="$label" -PguTechAssets="$assets" -PguTechConnectome="$connectome"
 apk="$OUT_DIR/FlyConsole-AGOD-2.2.0-$id-debug.apk"
 cp app/build/outputs/apk/debug/app-debug.apk "$apk"

 # ---- verify what is really inside ----
 package=$("$AAPT2" dump badging "$apk" | sed -n "s/^package: name='\([^']*\)'.*/\1/p")
 shown=$("$AAPT2" dump badging "$apk" | sed -n "s/^application-label:'\(.*\)'$/\1/p")
 inside=$(unzip -l "$apk" | awk '{print $4}')
 has_fly=$(echo "$inside" | grep -qx 'assets/brain.fly\(.gz\)\?' && echo yes || echo no)
 has_male=$(echo "$inside" | grep -qx 'assets/male-cns.fly\(.gz\)\?' && echo yes || echo no)
 want_fly=$([ "$assets" = flywire ] || [ "$assets" = both ] && echo yes || echo no)
 want_male=$([ "$assets" = male ] || [ "$assets" = both ] && echo yes || echo no)
 [ "$package" = "org.node.flyconsole.nes.tech.$lower" ] || { echo "WRONG PACKAGE $package"; exit 1; }
 [ "$shown" = "$label" ] || { echo "WRONG LABEL '$shown'"; exit 1; }
 [ "$has_fly" = "$want_fly" ] || { echo "FlyWire inside=$has_fly, wanted $want_fly"; exit 1; }
 [ "$has_male" = "$want_male" ] || { echo "Male CNS inside=$has_male, wanted $want_male"; exit 1; }
 # captured first: under pipefail, `unzip | grep -q` fails whenever grep stops
 # reading early and unzip takes SIGPIPE - which made a present file look absent
 carried=$(unzip -p "$apk" assets/lab/techtest-config.js)
 echo "$carried" | grep -q "id:'$id'" || { echo "techtest-config.js is not this build's"; exit 1; }
 echo "$inside" | grep -qx 'assets/lab/agod-live.js' || { echo "AGOD missing"; exit 1; }

 size=$(du -m "$apk" | cut -f1)
 (cd "$OUT_DIR" && sha256sum "$(basename "$apk")") >> "$OUT_DIR/SHA256SUMS"
 # if/fi, not `[ ] && echo`: the last test of an && chain returns 1 when false,
 # and under set -e that silently ended the whole script after a good build
 inside_txt=""
 if [ "$has_fly" = yes ]; then inside_txt="FlyWire"; fi
 if [ "$has_male" = yes ]; then inside_txt="${inside_txt:+$inside_txt + }MaleCNS"; fi
 if [ -z "$inside_txt" ]; then inside_txt="none"; fi
 echo "| $id | \`$package\` | $label | $inside_txt | $connectome | $autostart | $policy | $([ "$retry" = 0 ] && echo default || echo "${retry}s") | ${size} MB | $question |" >> "$OUT_DIR/TECHTEST_SET.md"
 echo "    ok: $package, '$shown', FlyWire=$has_fly MaleCNS=$has_male, ${size} MB"
done <<< "$SET"

{
 echo
 echo "## SHA-256"
 echo
 echo '```'
 cat "$OUT_DIR/SHA256SUMS"
 echo '```'
 echo
 echo "## What each APK was checked for after the build"
 echo
 echo "Package name, launcher label, which connectome files are physically inside the APK,"
 echo "that it carries its own techtest-config.js and the AGOD modules. None of the ten has"
 echo "been launched on a device by the build machine."
} >> "$OUT_DIR/TECHTEST_SET.md"
echo "done: $OUT_DIR"
